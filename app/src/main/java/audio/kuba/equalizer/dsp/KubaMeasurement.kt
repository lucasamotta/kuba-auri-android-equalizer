    /**
     * Retorna a curva alvo para exibição no gráfico.
     * Para as curvas de preferência e customizadas, a referência oficial é 'padrao' (JM-1).
     * Harman usa 'harman', Referência usa 'referencia', Basshead usa 'basshead', Analítico usa 'analitico'.
     */
    fun getTargetCurve(preset: Preset): DoubleArray {
        return when (preset.id) {
            "harman" -> targetHarman
            "referencia" -> targetReferencia
            "basshead" -> targetBasshead
            "analitico" -> targetAnalitico
            else -> targetPadrao // Sempre JM-1 para Auri, Natural, Em V, Enérgico, Musical e CUSTOM (equalizador personalizado)
        }
    }

    /**
     * Calcula a curva resultante (resposta do fone + equalização DSP aplicada),
     * alinhada ao alvo JM-1 (padrao) pela média entre 300 Hz e 3 kHz.
     * Exatamente a mesma fórmula e lógica de resultCurve() do web-app oficial.
     */
    fun calculateResultCurve(preset: Preset): DoubleArray {
        val bandsToEvaluate = preset.showBands ?: preset.bands
        val tg = getTargetCurve(preset)
        val raw = DoubleArray(frequencies.size) { i ->
            rawDb[i] + DspProtocol.calculateResponseDb(bandsToEvaluate, frequencies[i])
        }

        var sum = 0.0
        var count = 0
        for (i in frequencies.indices) {
            val f = frequencies[i]
            if (f in 300.0..3000.0) {
                sum += raw[i] - tg[i]
                count++
            }
        }
        val offset = if (count > 0) sum / count else 0.0
        return DoubleArray(raw.size) { i -> raw[i] - offset }
    }

    /**
     * Calcula a escala Y (dB mínimo e máximo) com folga e passo de 5 dB,
     * garantindo um range visual confortável e não distorcido/comprimido.
     */
    fun calculateYRange(resultCurve: DoubleArray, targetCurve: DoubleArray): Pair<Double, Double> {
        var lo = Double.POSITIVE_INFINITY
        var hi = Double.NEGATIVE_INFINITY

        for (i in frequencies.indices) {
            if (frequencies[i] <= 16000.0) {
                lo = min(lo, min(resultCurve[i], targetCurve[i]))
                hi = max(hi, max(resultCurve[i], targetCurve[i]))
            }
        }

        var loRounded = max(floor(lo / 5.0) * 5.0, -20.0)
        var hiRounded = ceil(hi / 5.0) * 5.0

        if (hiRounded - loRounded < 40.0) {
            val pad = ceil((40.0 - (hiRounded - loRounded)) / 10.0) * 5.0
            loRounded -= pad
            hiRounded += pad
        }

        return Pair(loRounded, hiRounded)
    }
